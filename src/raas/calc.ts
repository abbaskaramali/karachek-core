import { addDaysToJalali, getTodayJalali, jalaliToIsoSafe } from '../utils';

/**
 * ═══════════════════════════════════════════════════════════════════
 *  محاسبه‌ی راس — یک منبع واحد برای همه‌ی نمایش‌ها
 * ═══════════════════════════════════════════════════════════════════
 *  پنل کاربری، فاکتور چاپی، اشتراک‌گذاری، لیست ذخیره‌ها و دموی صفحه‌ی
 *  عمومی همگی همین توابع را صدا می‌زنند. تا وقتی هر کدام نسخه‌ی خودش
 *  را داشت، یک اصلاح در فرمول یعنی چهار جای دیگر که ساکت غلط می‌مانند —
 *  و بدترین حالت این است که کاربر یک عدد را روی صفحه ببیند و عدد
 *  دیگری را روی فاکتوری که به مشتری می‌دهد.
 *
 *  ── دو خروجی، دو معنا
 *
 *  ۱) «تاریخ راس» (تاریخ تسویه‌ی واحد) — خروجی اصلیِ راس‌گیری فاکتور.
 *     اگر مشتری به‌جای پرداخت جداگانه‌ی چند فاکتور، یک پرداخت یکجا کند،
 *     سررسید آن پرداخت باید این تاریخ باشد تا ارزش زمانی پول برای هیچ
 *     طرف تغییر نکند.
 *
 *  ۲) «بهره / مبلغ دریافتی خالص» — خروجی راس‌گیری چک (تنزیل).
 *
 *  ⚠️ و تفاوت حیاتی این دو، که همه‌جا اشتباه می‌شود:
 *
 *     تاریخ راس  →  به انتخاب مبدا **وابسته نیست**
 *     مبلغ بهره   →  به انتخاب مبدا **کاملاً وابسته است**
 *
 *  چون تاریخ راس = مبدا + میانگین روزها؛ مبدا را جلو ببرید، میانگین به
 *  همان اندازه کم می‌شود و مجموع سر جایش می‌ماند. اما بهره مستقیماً در
 *  همان میانگین ضرب می‌شود و هیچ‌چیز خنثی‌اش نمی‌کند.
 *
 *  به همین دلیل مبدای خودکار در دو حالت فرق دارد: برای فاکتور
 *  قدیمی‌ترین تاریخ صدور (مرسوم حسابداری، و چون روی جواب اثر ندارد
 *  کاملاً آزاد است)، و برای چک «امروز» (چون تنزیل از امروز است).
 * ═══════════════════════════════════════════════════════════════════
 */

export type RaasRounding = 'ROUND_UP' | 'ROUND_DOWN' | 'NONE';

/** حداقلِ چیزی که برای محاسبه لازم است — هم رکورد دیتابیس و هم ردیف دمو با آن جور است */
export type RaasCalcRow = {
   amount: number;
   /** فاصله‌ی علامت‌دار مبدا تا سررسید (منفی = سند معوق) */
   days_diff: number;
   /** فقط فاکتور: مهلت تسویه‌ی توافقی */
   term_days?: number | null;
};

/**
 * میانگین وزنیِ روزها — قلب راس‌گیری.
 *
 *     روز راس = Σ(مبلغ × روز) ÷ Σ(مبلغ)
 *
 * ⚠️ وزن، *مبلغ* است و نه چیز دیگر. میانگین ساده (بدون وزن) یک فاکتور
 * یک‌میلیونی را هم‌ارز یک فاکتور صدمیلیونی می‌گیرد و جوابش با اصل ارزش
 * زمانی پول جور در نمی‌آید. آن عدد اگر لازم باشد «میانگین مهلت فروش»
 * است، نه راس.
 */
export const raas_average_days_exact = (rows: RaasCalcRow[], ignore_amount = false): number => {
   /**
    * ═══════════════════════════════════════════════════════════════
    *  حالت «مستقل از مبلغ» — فقط فاکتور، و فقط با تنظیم کاربر
    * ═══════════════════════════════════════════════════════════════
    *  در این حالت میانگینِ *ساده‌ی* روزها گرفته می‌شود و مبلغ هیچ اثری
    *  ندارد. یعنی یک فاکتور یک‌میلیونی و یک فاکتور صدمیلیونی هم‌وزن‌اند.
    *
    *  ⚠️ این عدد دیگر «راس» به معنای مالیِ کلمه نیست؛ «میانگین مهلت
    *  فروش» است. از نظر ارزش زمانی پول، جوابِ درستِ تسویه همان میانگینِ
    *  وزنی است. ولی بعضی کسب‌وکارها عمداً این را می‌خواهند — وقتی
    *  فاکتورها تقریباً هم‌اندازه‌اند یا وقتی قرار است فقط یک تاریخِ
    *  میانگینِ ساده به مشتری اعلام شود.
    *
    *  پس این یک *انتخاب* است و نه یک اصلاح، و به همین دلیل:
    *   • پیش‌فرض خاموش است (رفتار فعلی سایت دست‌نخورده می‌ماند)
    *   • فقط در حالت فاکتور اعمال می‌شود؛ در راس‌گیری چک که خروجی
    *     «بهره» است، میانگینِ بی‌وزن عددِ بی‌معنی می‌دهد
    *
    *  ⚠️ پارامتر پیش‌فرض `false` است تا همه‌ی فراخوانی‌های موجود بدون
    *  تغییر، دقیقاً همان رفتار قبلی را داشته باشند.
    */
   if (ignore_amount) {
      if (!rows.length) return 0;
      return rows.reduce((s, r) => s + r.days_diff, 0) / rows.length;
   }
   const total = rows.reduce((s, r) => s + r.amount, 0);
   if (!total) return 0;
   return rows.reduce((s, r) => s + r.amount * r.days_diff, 0) / total;
};

/**
 * ═══════════════════════════════════════════════════════════════════
 *  نحوه‌ی نمایش مبلغ کل — کسر بهره یا افزودن بهره
 * ═══════════════════════════════════════════════════════════════════
 *  دو کاربردِ متفاوتِ یک محاسبه:
 *
 *   • `SUBTRACT` (پیش‌فرض) — «چک‌ها را امروز نقد می‌کنم، چقدر به دستم
 *     می‌رسد؟» بهره از جمع کل کم می‌شود. این همان تنزیل است.
 *
 *   • `ADD` — «مشتری می‌خواهد دیرتر پرداخت کند، چقدر باید بدهد؟»
 *     بهره به جمع کل اضافه می‌شود.
 *
 *  ⚠️ فقط *جهتِ* عدد فرق می‌کند؛ خودِ بهره در هر دو حالت یکسان حساب
 *  می‌شود (جمع کل × نرخ × روز راس ÷ ۳۰). پس این تنظیم هیچ‌وقت مبلغ
 *  بهره را عوض نمی‌کند، فقط می‌گوید با آن چه کنیم.
 */
export type RaasInterestMode = 'SUBTRACT' | 'ADD';

export const raas_net_amount = (total: number, interest: number, mode: RaasInterestMode): number =>
   mode === 'ADD' ? total + interest : total - interest;

/** برچسبِ عددِ نهایی — با جهتِ محاسبه عوض می‌شود، وگرنه «خالص» روی عددی می‌نشست که بزرگ‌تر از جمع کل است */
export const raas_net_label = (mode: RaasInterestMode): string =>
   mode === 'ADD' ? 'مبلغ قابل پرداخت (با بهره)' : 'مبلغ دریافتی (خالص)';

export const RAAS_INTEREST_MODE_LABEL: Record<RaasInterestMode, string> = {
   SUBTRACT: 'بهره از جمع کل کسر شود',
   ADD: 'بهره به جمع کل اضافه شود',
};

/** اعمال تنظیم گردکردنِ پروفایل کاربر روی روز راس */
export const apply_rounding = (days: number, rounding: RaasRounding): number =>
   rounding === 'ROUND_UP' ? Math.ceil(days)
      : rounding === 'ROUND_DOWN' ? Math.floor(days)
         : days;

/**
 * تاریخ راس = مبدا + روز راس.
 *
 * ⚠️ اینجا جایی است که بیشترین خطای «یک روز» ساخته می‌شود، و آن یک روز
 * روی یک تسویه‌ی چندصدمیلیونی پول واقعی است. دو قاعده:
 *
 *  ۱) هیچ گردکردنِ *میانی* نداشته باشید. اگر میانگینِ تاریخ‌های صدور را
 *     اول گرد کنید و بعد میانگین مهلت‌ها را به آن اضافه کنید، کسرِ
 *     دورریخته‌شده تا یک روز جواب را جابه‌جا می‌کند. مبدا باید یک تاریخِ
 *     واقعیِ صحیح باشد و تنها گردکردن، در آخرین گام.
 *
 *  ۲) تبدیل عددِ کسری به یک روزِ تقویمی با `Math.floor` انجام می‌شود —
 *     یعنی «روزی که لحظه‌ی دقیقِ راس داخلش می‌افتد». راسِ ۶۰.۰۶ روز بعد
 *     از مبدا، ساعتِ ۱ بامدادِ روزِ شصتم است؛ پس روزِ شصتم جواب است، نه
 *     شصت‌ویکم. این همان معنای «رند نشود» است.
 *
 *     ⚠️ با تنظیمِ ROUND_UP / ROUND_DOWN تداخلی ندارد: آن تنظیم *پیش از
 *     این* روی خودِ عدد اعمال شده و عدد را صحیح کرده، پس اینجا floor
 *     کاری نمی‌کند. عددِ دقیقِ اعشاری جدا نمایش داده می‌شود.
 *
 * @param base_date_jalali مبدا به شمسی `YYYY/MM/DD`
 * @param average_days     روز راس (پس از اعمال تنظیم گردکردن)
 */
export const raas_date_jalali = (base_date_jalali: string, average_days: number): string => {
   if (!base_date_jalali || !Number.isFinite(average_days)) return '';
   return addDaysToJalali(base_date_jalali, Math.floor(average_days));
};

/**
 * همان تاریخ راس، ولی از یک مبدای میلادی (همان چیزی که در دیتابیس است)
 * و به‌صورت `Date`.
 *
 * ⚠️ چرا دو نسخه؟ چون ارقام. جدول‌ها و PDF همه‌ی تاریخ‌ها را از
 * `jalali_date` می‌گیرند که ارقام فارسی می‌دهد؛ اگر تاریخ راس را
 * به‌صورت رشته‌ی شمسیِ لاتین کنارشان می‌گذاشتیم، در یک ستون دو جور رقم
 * دیده می‌شد. پس هرجا مبدا را به‌صورت تاریخ داریم، خروجی هم `Date` است
 * تا از همان قالب‌بندیِ مشترک رد شود.
 */
export const raas_date_from = (base_date: Date | string | null | undefined, average_days: number): Date | null => {
   if (!base_date || !Number.isFinite(average_days)) return null;
   const t = new Date(base_date).getTime();
   if (isNaN(t)) return null;
   return new Date(t + Math.floor(average_days) * 86400000);
};

/** روز هفته‌ی یک تاریخ میلادی، به وقت تهران */
const weekday_formatter = new Intl.DateTimeFormat('fa-IR', { timeZone: 'Asia/Tehran', weekday: 'long' });
export const weekday_of = (value: Date | string | null | undefined): string => {
   if (!value) return '';
   const d = new Date(value);
   return isNaN(d.getTime()) ? '' : weekday_formatter.format(d);
};

/**
 * میانگین وزنیِ «دوره‌ی اعتباری» — یعنی مهلتی که به‌طور میانگین به مشتری
 * داده شده است.
 *
 * این عددِ دومی است که در راس‌گیری فاکتور معنا دارد: تاریخ راس می‌گوید
 * *کِی* باید تسویه شود، و این می‌گوید *چقدر* اعتبار داده‌ایم. برای سنجش
 * سیاست فروش به کار می‌آید، نه برای تسویه.
 *
 * ⚠️ فقط روی ردیف‌هایی حساب می‌شود که مهلت ثبت‌شده دارند؛ اگر هیچ‌کدام
 * نداشتند `null` برمی‌گردد تا به‌جای «۰ روز» چیزی نمایش داده نشود.
 */
export const raas_average_term = (rows: RaasCalcRow[], ignore_amount = false): number | null => {
   const withTerm = rows.filter(r => r.term_days != null && Number.isFinite(Number(r.term_days)));
   if (!withTerm.length) return null;
   /**
    * ⚠️ همان تنظیمِ «مستقل از مبلغ» اینجا هم اعمال می‌شود، و اجباری است
    * که هر دو با هم عوض شوند: اگر روز راس بی‌وزن حساب شود ولی میانگین
    * مهلت وزنی بماند، کاربر دو عددِ میانگین کنار هم می‌بیند که با دو
    * قاعده‌ی متفاوت درآمده‌اند و هیچ‌کدام دیگری را توضیح نمی‌دهد.
    */
   if (ignore_amount) {
      return withTerm.reduce((s, r) => s + Number(r.term_days), 0) / withTerm.length;
   }
   const total = withTerm.reduce((s, r) => s + r.amount, 0);
   if (!total) return null;
   return withTerm.reduce((s, r) => s + r.amount * Number(r.term_days), 0) / total;
};

/** نمایش عدد روز: صحیح بدون اعشار، کسری با دو رقم */
export const format_days = (days: number): string =>
   Number.isInteger(days) ? String(days) : days.toFixed(2);

/**
 * روز هفته‌ی یک تاریخ شمسی — برای اینکه کاربر پیش از دادن تاریخ تسویه
 * به مشتری ببیند آن روز جمعه یا تعطیل نیست.
 */
const WEEKDAYS = ['یکشنبه', 'دوشنبه', 'سه‌شنبه', 'چهارشنبه', 'پنجشنبه', 'جمعه', 'شنبه'];
export const jalali_weekday = (jalali: string): string => {
   // ⚠️ `jalaliToIsoSafe` نیمه‌شبِ UTC می‌سازد و `getUTCDay` هم UTC می‌خواند؛
   // اگر یکی از این دو محلی بود، روز هفته روی مرز نیمه‌شب یکی جابه‌جا می‌شد.
   const iso = jalaliToIsoSafe(jalali);
   if (!iso) return '';
   return WEEKDAYS[new Date(iso).getUTCDay()];
};

/** «امروز» به شمسی — همان مبدای خودکارِ حالت چک */
export const today_jalali = (): string => getTodayJalali();
